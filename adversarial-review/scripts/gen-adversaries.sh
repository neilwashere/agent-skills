#!/usr/bin/env bash
# gen-adversaries.sh — stamp per-model adversary agent files from ONE template.
#
# The reviewer prompt lives once in assets/adversary.prompt.md. This script wraps
# it in agent frontmatter (name/description/tools/model) for each model you name,
# so the `subagent` tool can dispatch each on a different model with no duplicated
# prompt text.
#
# Usage:
#   gen-adversaries.sh [--dir DIR] [--user] [--tools "t1,t2"] [--clean] SPEC...
#
#   SPEC        provider/model   or   provider/model=alias
#               e.g. deepseek/deepseek-v4-pro
#                    amazon-bedrock/eu.anthropic.claude-opus-4-8=opus
#   --dir DIR   target agents dir (default: ./.pi/agents)
#   --user      target ~/.pi/agent/agents instead of the project dir
#   --tools     comma tool list (default: read,grep,find,ls,bash)
#   --clean     remove existing adversary-*.md in the target dir first
#
# Prints the generated agent names so you can dispatch them immediately.
set -euo pipefail

SKILL_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PROMPT="$SKILL_DIR/assets/adversary.prompt.md"
[ -f "$PROMPT" ] || { echo "gen-adversaries: missing template $PROMPT" >&2; exit 1; }

DIR=".pi/agents"
TOOLS="read,grep,find,ls,bash"
CLEAN=0
SPECS=()

while [ $# -gt 0 ]; do
  case "$1" in
    --dir)   DIR="$2"; shift 2;;
    --user)  DIR="$HOME/.pi/agent/agents"; shift;;
    --tools) TOOLS="$2"; shift 2;;
    --clean) CLEAN=1; shift;;
    -h|--help) sed -n '2,22p' "$0"; exit 0;;
    -*) echo "gen-adversaries: unknown flag $1" >&2; exit 2;;
    *)  SPECS+=("$1"); shift;;
  esac
done

[ "${#SPECS[@]}" -gt 0 ] || { echo "gen-adversaries: name at least one provider/model spec" >&2; exit 2; }

mkdir -p "$DIR"
if [ "$CLEAN" -eq 1 ]; then
  rm -f "$DIR"/adversary-*.md
  echo "cleaned $DIR/adversary-*.md"
fi

# The shared reviewer body (single source of truth), minus its own H1 title line.
# REVIEWER_TAG is substituted per-model below so each agent self-identifies
# (Path B / dispatch-subagents does this substitution itself on the raw template).
RAW_BODY="$(tail -n +2 "$PROMPT")"

slugify() { echo "$1" | tr '[:upper:]' '[:lower:]' | sed -E 's/[^a-z0-9]+/-/g; s/^-+|-+$//g'; }

names=()
for spec in "${SPECS[@]}"; do
  model="${spec%%=*}"
  if [ "$spec" != "$model" ]; then alias="${spec#*=}"; else alias="${model##*/}"; fi
  slug="$(slugify "$alias")"
  name="adversary-$slug"
  out="$DIR/$name.md"
  body="${RAW_BODY//REVIEWER_TAG/the $model adversary}"
  {
    echo "---"
    echo "name: $name"
    echo "description: Adversarial code reviewer ($model). Hunts for real defects in a diff. Generated by the adversarial-review skill — edit assets/adversary.prompt.md, not this file."
    echo "tools: $TOOLS"
    echo "model: $model"
    echo "---"
    echo
    echo "$body"
  } > "$out"
  names+=("$name")
  echo "wrote $out  (model: $model)"
done

echo
echo "dispatch these with the subagent tool (agentScope: both, confirmProjectAgents: false):"
printf '  %s\n' "${names[@]}"
