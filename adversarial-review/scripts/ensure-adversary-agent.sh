#!/usr/bin/env bash
# ensure-adversary-agent.sh — write ONE shared "adversary" agent from the
# single-source-of-truth template, for dispatch via the subagent tool's
# per-task `model` override (no more per-model agent files).
#
# Historically this script (gen-adversaries.sh) stamped one throwaway agent
# file PER MODEL, because the subagent tool dispatches by agent name and an
# agent's model used to have to live in its own frontmatter. pi-subagents now
# accepts `model` as a per-task override in a single `tasks: [...]` call, so
# one static agent, reused across every model in the panel, is enough:
#
#   subagent({ tasks: [
#     { agent: "adversary", task: "<shared task>", model: "deepseek/deepseek-v4-pro" },
#     { agent: "adversary", task: "<shared task>", model: "zai-coding-cn/glm-5.2" },
#     { agent: "adversary", task: "<shared task>", model: "moonshotai/kimi-k2.7-code" },
#   ] })
#
# The template's REVIEWER_TAG token is still the single source of truth used
# by the detached-CLI fallback (dispatch-subagents' dispatch.sh substitutes it
# per model at dispatch time, once per process). For this shared, model-agnostic
# agent file there's no single model identity to bake in, so REVIEWER_TAG is
# substituted once with a generic phrase here. Structured per-model attribution
# for the in-harness path comes from the subagent tool's own result.model
# field, not from prompt text — see the dispatch-subagents skill.
#
# Usage:
#   ensure-adversary-agent.sh [--dir DIR] [--user] [--tools "t1,t2"] [--force]
#
#   --dir DIR   target agents dir (default: ./.pi/agents)
#   --user      target ~/.pi/agent/agents instead of the project dir
#   --tools     comma tool list (default: read,grep,find,ls,bash)
#   --force     overwrite an existing adversary.md even if content differs
#
# Idempotent: re-running with unchanged inputs is a no-op. Prints the agent
# name to dispatch once written or already up to date.
set -euo pipefail

SKILL_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PROMPT="$SKILL_DIR/assets/adversary.prompt.md"
[ -f "$PROMPT" ] || { echo "ensure-adversary-agent: missing template $PROMPT" >&2; exit 1; }

DIR=".pi/agents"
TOOLS="read,grep,find,ls,bash"
FORCE=0

while [ $# -gt 0 ]; do
  case "$1" in
    --dir)   [ $# -ge 2 ] || { echo "ensure-adversary-agent: --dir requires a value" >&2; exit 2; }; DIR="$2"; shift 2;;
    --user)  DIR="$HOME/.pi/agent/agents"; shift;;
    --tools) [ $# -ge 2 ] || { echo "ensure-adversary-agent: --tools requires a value" >&2; exit 2; }; TOOLS="$2"; shift 2;;
    --force) FORCE=1; shift;;
    -h|--help) sed -n '2,35p' "$0"; exit 0;;
    -*) echo "ensure-adversary-agent: unknown flag $1" >&2; exit 2;;
    *)  echo "ensure-adversary-agent: unexpected arg '$1' (no per-model specs anymore — model is a dispatch-time task param)" >&2; exit 2;;
  esac
done

mkdir -p "$DIR"
OUT="$DIR/adversary.md"

# The shared reviewer body (single source of truth), minus its own H1 title
# line. Generic substitution: this agent is reused across every model in the
# panel, so there's no single model identity to stamp into REVIEWER_TAG here.
RAW_BODY="$(tail -n +2 "$PROMPT")"
BODY="${RAW_BODY//REVIEWER_TAG/one of several independent reviewers in a multi-model panel}"

NEW_CONTENT="$(
  echo "---"
  echo "name: adversary"
  echo "description: Adversarial code reviewer. Hunts for real defects in a diff. Dispatch with a per-task model override via the subagent tool. Generated by the adversarial-review skill — edit assets/adversary.prompt.md, not this file."
  echo "tools: $TOOLS"
  echo "---"
  echo
  printf '%s\n' "$BODY"
)"

if [ -f "$OUT" ] && [ "$FORCE" -ne 1 ]; then
  if [ "$(cat "$OUT")" = "$NEW_CONTENT" ]; then
    echo "up to date: $OUT"
    echo "dispatch with the subagent tool, one task per model, e.g.:"
    echo '  tasks: [{ agent: "adversary", task: "...", model: "deepseek/deepseek-v4-pro" }, ...]'
    exit 0
  fi
  echo "ensure-adversary-agent: $OUT exists with different content — rerun with --force to overwrite" >&2
  exit 1
fi

printf '%s\n' "$NEW_CONTENT" > "$OUT"
echo "wrote $OUT"
echo "dispatch with the subagent tool, one task per model, e.g.:"
echo '  tasks: [{ agent: "adversary", task: "...", model: "deepseek/deepseek-v4-pro" }, ...]'
